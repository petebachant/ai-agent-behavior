"""Check whether every run's write-up reports the same, correct moduli.

For each run of the reproducibility and use-calkit experiments, the elastic
modulus its write-up reports for each material is read from the first
table row naming the material, or else the first sentence that does: the
first number there in the material's plausible range. Each is compared
with the modulus computed here from the data, at the precision the write-up
gives it. Either of two estimates counts as correct: a fit to all of a
material's points, or the mean of its specimens' fits, which agree here
since every specimen was tested at the same strains.

A reported value that doesn't match is also looked for among the numbers
in the run's own output files (CSV, JSON, and text), at the same
precision, to tell a number the analysis produced from one only in the
write-up, and traced through the run: the write-up's line that reports it,
the value its saved script printed (from the session transcript), the
specimen moduli as its output files hold them, and any other command whose
output gave the reported value to more precision. The write-up, that
output file, and those commands with their output are copied to
``results/numerical-agreement/<run>/`` so they can be cited; each is
declared as an output of this stage in ``calkit.yaml``, since a file inside
an output directory isn't yet attributed to the stage that writes it.

Whether each write-up was generated by the run's own pipeline, i.e., is an
output in its ``dvc.yaml``, so its numbers come from results files rather
than being typed in, is recorded too.
"""

import csv
import json
import re
import shutil
import sys
from collections import defaultdict
from pathlib import Path
from statistics import mean

from common import REPO, extracted, load_runs, write_json
from score_reproducibility import pipeline_outputs, write_ups

EXPERIMENTS = ["reproducibility", "use-calkit"]
DATA = (REPO / "experiments" / "reproducibility" / "fixtures" / "default"
        / "measurements.csv")
MATERIALS = ["aluminum", "steel", "titanium"]
# GPa; wide enough for any sensible estimate, narrow enough to skip other
# numbers near the material's name, e.g., R² or a strain
PLAUSIBLE = {"aluminum": (60, 80), "steel": (185, 215),
             "titanium": (105, 125)}
NUMBER = re.compile(r"(?<![\d.])(\d{2,3}(?:\.\d{1,4})?)(?![\d.])")
OUTPUT_EXT = {".csv", ".json", ".txt", ".tsv"}
SCRIPT_EXT = {".py", ".r", ".jl", ".sh"}
SKIP_DIRS = {".venv", ".calkit", ".git", ".dvc"}
TRACES = REPO / "results" / "numerical-agreement"


def slope(points: list[tuple[float, float]]) -> float:
    """The ordinary least-squares slope of a line with an intercept."""
    x_mean = mean(x for x, _ in points)
    y_mean = mean(y for _, y in points)
    return (sum((x - x_mean) * (y - y_mean) for x, y in points)
            / sum((x - x_mean) ** 2 for x, _ in points))


def correct_moduli() -> dict[str, list[float]]:
    """Each material's modulus in GPa, pooled and as the specimen mean."""
    with DATA.open() as f:
        rows = list(csv.DictReader(f))
    out = {}
    for material in MATERIALS:
        by_specimen = defaultdict(list)
        for r in rows:
            if r["material"] == material:
                by_specimen[r["specimen"]].append(
                    (float(r["strain"]), float(r["stress_mpa"])))
        pooled = slope([pt for pts in by_specimen.values() for pt in pts])
        specimens = [slope(pts) for pts in by_specimen.values()]
        out[material] = [pooled / 1e3, mean(specimens) / 1e3]
    return out


def write_up(ws: Path) -> str:
    return "\n".join(p.read_text(errors="replace") for p in write_ups(ws))


def tool_runs(run: dict) -> list[tuple[str, str]]:
    """Each shell command the agent ran, with its output, in order."""
    runs, pending = [], {}
    path = run["session_dir"] / "transcript.jsonl"
    for line in path.read_text().splitlines():
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not isinstance(event, dict):
            continue
        kind = event.get("type")
        if run["cli"] == "claude":
            content = (event.get("message") or {}).get("content")
            for block in content if isinstance(content, list) else []:
                if block.get("type") == "tool_use" and block.get(
                        "name") == "Bash":
                    pending[block["id"]] = len(runs)
                    runs.append([block["input"].get("command", ""), ""])
                elif (block.get("type") == "tool_result"
                      and block.get("tool_use_id") in pending):
                    out = block.get("content")
                    if isinstance(out, list):
                        out = "\n".join(b.get("text", "") for b in out)
                    runs[pending[block["tool_use_id"]]][1] = str(out or "")
        elif run["cli"] == "codex" and kind == "item.completed":
            item = event.get("item", {})
            if item.get("type") == "command_execution":
                runs.append([item.get("command", ""),
                             item.get("aggregated_output", "")])
        elif run["cli"] == "opencode" and kind == "tool_use":
            part = event.get("part", {})
            if part.get("tool") in ("bash", "shell"):
                state = part.get("state", {})
                runs.append([state.get("input", {}).get("command", ""),
                             str(state.get("output", ""))])
    return [tuple(r) for r in runs]


def specimen_ids(material: str) -> list[str]:
    with DATA.open() as f:
        return sorted({r["specimen"] for r in csv.DictReader(f)
                       if r["material"] == material})


def trace(run: dict, ws: Path, material: str, value: str,
          out_dir: Path) -> dict:
    """Where a mismatched value came from, with the files to cite."""
    lo, hi = PLAUSIBLE[material]
    d = decimals(value)
    out_dir.mkdir(parents=True)
    found: dict = {}
    # The write-up's line reporting it
    for p in write_ups(ws):
        for i, line in enumerate(p.read_text(errors="replace").splitlines(),
                                 start=1):
            if material in line.lower() and value in line:
                found.update(writeup_file=p.name, writeup_line=i,
                             writeup_text=line.strip())
                shutil.copy(p, out_dir / p.name)
                break
        if "writeup_file" in found:
            break
    # The specimen moduli as an output file holds them
    ids = specimen_ids(material)
    for p in sorted(ws.rglob("*")):
        rel = p.relative_to(ws)
        if (not p.is_file() or p.suffix.lower() not in OUTPUT_EXT
                or set(rel.parts) & SKIP_DIRS or p.name == DATA.name):
            continue
        vals = {}
        for line in p.read_text(errors="replace").splitlines():
            for sid in ids:
                if sid in line and sid not in vals:
                    nums = [n for n in NUMBER.findall(line)
                            if lo <= float(n) <= hi]
                    if nums:
                        vals[sid] = float(nums[0])
        if len(vals) == len(ids):
            found.update(output_file=str(rel),
                         output_values=[vals[s] for s in ids],
                         output_mean=mean(vals.values()))
            shutil.copy(p, out_dir / p.name)
            break
    # What the saved script printed, and other commands that gave the value
    scripts = {p.name for p in ws.rglob("*")
               if p.suffix.lower() in SCRIPT_EXT
               and not set(p.relative_to(ws).parts) & SKIP_DIRS}
    for i, (cmd, out) in enumerate(tool_runs(run), start=1):
        if any(s in cmd for s in scripts):
            lines = [ln for ln in out.splitlines()
                     if material in ln.lower() and "mean" in ln.lower()]
            v = reported("\n".join(lines), material)
            if v is not None:
                found.update(script_value=float(v), script_command=i)
                (out_dir / "script-output.txt").write_text(
                    f"$ {cmd}\n{out}\n")
            continue
        for line in out.splitlines():
            if material not in line.lower():
                continue
            for n in NUMBER.findall(line):
                if decimals(n) > d and round(float(n), d) == float(value):
                    found.update(oneoff_value=float(n), oneoff_command=i)
                    (out_dir / "one-off-command.txt").write_text(
                        f"$ {cmd}\n{out}\n")
    found["files"] = sorted(str(p.relative_to(REPO))
                            for p in out_dir.iterdir())
    return found


def reported(text: str, material: str) -> str | None:
    lo, hi = PLAUSIBLE[material]
    for pattern in [rf"^\|\s*\**{material}\**\s*\|.*$",
                    rf"{material}[^\n]{{0,80}}"]:
        for m in re.finditer(pattern, text, re.IGNORECASE | re.MULTILINE):
            for value in NUMBER.findall(m.group(0)):
                if lo <= float(value) <= hi:
                    return value
    return None


def decimals(value: str) -> int:
    return len(value.split(".")[1]) if "." in value else 0


def matches(value: str, candidates: list[float]) -> bool:
    d = decimals(value)
    return any(round(c, d) == round(float(value), d) for c in candidates)


def output_numbers(ws: Path) -> list[float]:
    numbers = []
    for p in ws.rglob("*"):
        rel = p.relative_to(ws)
        if (p.is_file() and p.suffix.lower() in OUTPUT_EXT
                and not set(rel.parts) & SKIP_DIRS and p.name != DATA.name):
            numbers += [float(n) for n in
                        NUMBER.findall(p.read_text(errors="replace"))]
    return numbers


def main() -> None:
    correct = correct_moduli()
    if TRACES.exists():
        shutil.rmtree(TRACES)
    runs = []
    for experiment in EXPERIMENTS:
        for run in load_runs(experiment):
            if not run["ok"]:
                continue
            with extracted(run["workspace_tar"]) as ws:
                text = write_up(ws)
                values = {m: reported(text, m) for m in MATERIALS}
                outputs = output_numbers(ws)
                generated = pipeline_outputs(ws)
                record_ws = [str(p.relative_to(ws)) for p in write_ups(ws)]
                bad = [m for m, v in values.items()
                       if v is not None and not matches(v, correct[m])]
                traces = {
                    m: trace(run, ws, m, values[m], TRACES / (
                        f"{experiment}-" + run["run_id"].replace("/", "-")))
                    for m in bad
                }
            record = {
                "experiment": experiment,
                "run_id": run["run_id"],
                "agent": run["agent"],
                "condition": run["condition"],
                "reported": values,
                "correct": {m: v is not None and matches(v, correct[m])
                            for m, v in values.items()},
                "writeup_generated": bool(record_ws)
                and all(p in generated for p in record_ws),
                "traces": traces,
            }
            record["in_outputs"] = {
                m: matches(v, outputs) for m, v in values.items()
                if v is not None and not record["correct"][m]
            }
            runs.append(record)
    if any(v is None for r in runs for v in r["reported"].values()):
        missing = [r["run_id"] for r in runs if None in r["reported"].values()]
        sys.exit(f"No modulus found in the write-ups of {missing}")
    mismatches = [
        {"experiment": r["experiment"], "run_id": r["run_id"],
         "agent": r["agent"], "material": m,
         "reported": float(r["reported"][m]),
         "correct": correct[m][1], "in_outputs": r["in_outputs"][m],
         "trace": r["traces"].get(m, {})}
        for r in runs for m in MATERIALS if not r["correct"][m]
    ]
    groups = defaultdict(list)
    for r in runs:
        groups[f"{r['experiment']}/{r['condition']}"].append(
            r["writeup_generated"])
    distinct = defaultdict(set)
    for r in runs:
        for m, v in r["reported"].items():
            distinct[m].add(round(float(v), 1))
    write_json(REPO / "results" / "numerical-agreement.json", {
        "description": __doc__.strip(),
        "correct_gpa": {m: {"pooled": v[0], "specimen_mean": v[1]}
                        for m, v in correct.items()},
        "summary": {
            "n_runs": len(runs),
            "n_all_correct": sum(all(r["correct"].values()) for r in runs),
            "n_mismatches": len(mismatches),
            "distinct_to_one_decimal": {m: sorted(v)
                                        for m, v in distinct.items()},
            "first_mismatch": mismatches[0] if mismatches else None,
            "frac_writeup_generated": {g: sum(v) / len(v)
                                       for g, v in sorted(groups.items())},
        },
        "mismatches": mismatches,
        "runs": runs,
    })


if __name__ == "__main__":
    main()
